#!/usr/bin/env python3
"""Verify selected original assets and runtime exports without changing them."""
import argparse
import collections
import hashlib
import json
from pathlib import Path

from PIL import Image

REPO = Path(__file__).resolve().parents[3]


def verify(relative, expected):
    root = REPO / relative
    manifest = json.loads((root / 'provenance.json').read_text())
    entries = manifest['entries']
    assert len(entries) == expected
    assert all(entry['status'] == 'generated' for entry in entries)
    assert len({entry['key'] for entry in entries}) == expected
    assert len({entry['name'] for entry in entries}) == expected
    originals, runtime = set(), set()
    source_sizes = collections.Counter()
    total_bytes, generated_checks = 0, 0
    sizes = manifest.get('runtime_sizes', [64, 128])
    for entry in entries:
        source = root / 'source' / (entry['name'] + '.png')
        raw = source.read_bytes()
        digest = hashlib.sha256(raw).hexdigest()
        assert digest == entry['source_sha256'], source
        generated = Path(entry['generated_path'])
        if generated.exists():
            assert raw == generated.read_bytes(), source
            generated_checks += 1
        originals.add(digest)
        image = Image.open(source)
        assert image.mode == 'RGBA', source
        source_sizes[str(image.size)] += 1
        total_bytes += len(raw)
        assert REPO / entry['runtime'] == root / (entry['name'] + '.tga'), entry['runtime']
        assert (REPO / entry['runtime']).is_file(), entry['runtime']
        for size in sizes:
            name = entry['name'] + ('' if size == max(sizes) else '-' + str(size)) + '.tga'
            path = root / name
            data = path.read_bytes()
            image = Image.open(path)
            assert image.mode == 'RGBA' and image.size == (size, size), path
            assert size > 0 and size & (size - 1) == 0, path
            assert data[2] == 2 and data[16] == 32 and data[17] & 15 == 8, path
            alpha = image.getchannel('A')
            assert alpha.getextrema()[0] == 0 and alpha.getextrema()[1] > 0, path
            corners = ((0, 0), (size - 1, 0), (0, size - 1), (size - 1, size - 1))
            assert all(alpha.getpixel(corner) == 0 for corner in corners), path
            total_bytes += len(data)
            if size == max(sizes):
                runtime.add(hashlib.sha256(image.tobytes()).hexdigest())
    assert len(originals) == expected, 'duplicate selected original image'
    assert len(runtime) == expected, 'duplicate selected decoded runtime image'
    return dict(selected_entries=len(entries), distinct_original_sha256=len(originals),
                distinct_decoded_main_runtime_sha256=len(runtime), runtime_sizes=sizes,
                source_sizes=dict(source_sizes), selected_source_and_runtime_bytes=total_bytes,
                generated_original_byte_checks=generated_checks), entries


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--inventory', type=Path, help='JSON from tools/collect_builtin_sources.lua')
    parser.add_argument('--report', type=Path)
    args = parser.parse_args()
    report = dict(native_acceptance='Not run; file checks and offline visual inspection only', sets={})
    icons = None
    for relative, expected in (('Assets/Conditions/v2', 130), ('Assets/Overlays/v1', 9)):
        result, entries = verify(relative, expected)
        report['sets'][relative] = result
        if relative.endswith('v2'):
            icons = entries
    if args.inventory:
        inventory = json.loads(args.inventory.read_text())
        actual = set()
        for module in inventory.values():
            if isinstance(module, dict):
                actual.update(module.get('conditions', {}))
                actual.update(module.get('conditionVariants', {}))
        covered = {entry['key'] for entry in icons if entry['kind'] == 'condition'}
        assert covered == actual, (covered - actual, actual - covered)
        assert {entry['key'] for entry in icons if entry['kind'] == 'logic'} == {'AND', 'OR', 'NOT'}
        categories = {entry['key'] for entry in icons if entry['kind'] == 'category'}
        assert categories == {'category-combat', 'category-character', 'category-spells',
                              'category-items', 'category-buffs', 'category-spatial',
                              'category-all', 'category-switch', 'category-other'}
        report['condition_inventory'] = dict(current_tags=len(actual), covered_tags=len(covered),
                                             missing=[], extra=[], categories=9, logical_controls=3)
    report['checks'] = ['selected source SHA256 matches manifest',
                        'original generated bytes match wherever original tool output is present',
                        'all sources RGBA and all runtime exports uncompressed type2 RGBA32 alpha8',
                        'expected power-of-two dimensions, transparent corners, nonempty alpha',
                        'no duplicate selected original or decoded main runtime image']
    content = json.dumps(report, indent=2) + '\n'
    if args.report:
        args.report.write_text(content)
    print(content, end='')


if __name__ == '__main__':
    main()
