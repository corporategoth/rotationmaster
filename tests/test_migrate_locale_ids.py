"""The one-time converter (tools/migrate_locale_ids.py) on a small tree in the OLD layout: no translation is lost, a
translation made from older English is stale by hash and never silently current, IDs follow file order, every file is
credited to the AI, and a second conversion of the result changes nothing."""
import json
from pathlib import Path
import shutil
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
import locale_format as F  # noqa: E402
import locales as L  # noqa: E402
import migrate_locale_ids as M  # noqa: E402

OLD_ENGLISH = '''local addon_name = ...

local L = LibStub("AceLocale-3.0"):NewLocale(addon_name, "enUS", true)
if not L then return end
L["Report"] = true
L["Pipe [a|b]"] = "Pipe [a||b]"
L["Default.X.Name"] = "Arms Warrior"
L["The current rotation is "..color.WHITE.."%s"..color.INFO] = true
-- BEGIN GENERATED RM PUBLIC HELPER DOCS
L["A generated description."] = true
-- END GENERATED RM PUBLIC HELPER DOCS
'''
OLD_GERMAN = '''-- Generated by tools/locales.py from reviewed translations; edit the
local addon_name = ...
local L = LibStub("AceLocale-3.0"):NewLocale(addon_name, "deDE")
if not L then return end
-- en: "Report"
L["Report"] = "Bericht"
-- en: "Pipe [a||b]"
L["Pipe [a|b]"] = "Rohr [a||b]"
-- en: "Arms"
L["Default.X.Name"] = "Waffen"
-- en: "The current rotation is |cFFFFFFFF%s|cFF7BC653"
L["The current rotation is |cFFFFFFFF%s|cFF7BC653"] = "Die aktuelle Rotation ist |cFFFFFFFF%s|cFF7BC653"
-- en: "A generated description."
L["A generated description."] = "Eine Beschreibung."
'''


class Migration(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        self.saved = L.ROOT
        L.ROOT = self.root
        L._cache.clear()
        (self.root / 'Locales').mkdir()
        (self.root / 'tools').mkdir()
        (self.root / 'Locales/enUS.lua').write_text(OLD_ENGLISH)
        (self.root / 'Locales/deDE.lua').write_text(OLD_GERMAN)
        (self.root / 'locales.xml').write_text('<Ui>\n<Script file="Locales\\enUS.lua" />\n<Script file="Locales\\deDE.lua" />\n</Ui>\n')
        shutil.copy(ROOT / 'globals.lua', self.root / 'globals.lua')

    def tearDown(self):
        L.ROOT = self.saved
        L._cache.clear()
        self.tmp.cleanup()

    def convert(self):
        import io
        import contextlib
        with contextlib.redirect_stdout(io.StringIO()):
            return M.convert(self.root)

    def test_ids_follow_file_order_and_every_translation_survives(self):
        stats = self.convert()
        english = L.english_entries()
        self.assertEqual([(e.id, e.key) for e in english], [
            (1, 'Report'), (2, 'Pipe [a|b]'), (3, 'Default.X.Name'),
            (4, 'The current rotation is |cFFFFFFFF%s|cFF7BC653'), (5, 'A generated description.')])
        self.assertEqual(L.by_key()['Pipe [a|b]'].text, 'Pipe [a||b]')
        self.assertEqual(dict(L.locale_entries('deDE')), {
            'Report': 'Bericht', 'Pipe [a|b]': 'Rohr [a||b]', 'Default.X.Name': 'Waffen',
            'The current rotation is |cFFFFFFFF%s|cFF7BC653': 'Die aktuelle Rotation ist |cFFFFFFFF%s|cFF7BC653',
            'A generated description.': 'Eine Beschreibung.'})
        self.assertEqual(stats['translations'], 5)
        registry = json.loads((self.root / L.REGISTRY_FILE).read_text())
        self.assertEqual(registry['next'], 6)
        self.assertEqual(registry['generated']['public-helper-docs'], [5])

    def test_a_translation_made_from_older_english_is_stale_by_hash(self):
        stats = self.convert()
        self.assertEqual(stats['stale'], 1)
        untranslated, stale = L.classify('deDE')
        self.assertEqual(untranslated, [])
        self.assertEqual([(e.key, t.english, t.text) for e, t in stale], [('Default.X.Name', 'Arms', 'Waffen')])
        self.assertEqual(stale[0][1].hash, F.text_hash('Arms'))
        self.assertNotEqual(stale[0][1].hash, F.text_hash('Arms Warrior'))

    def test_files_are_credited_to_the_ai_and_start_with_the_copyright_line(self):
        self.convert()
        for locale in ('enUS', 'deDE'):
            self.assertEqual((self.root / f'Locales/{locale}.lua').read_text().split('\n', 1)[0], F.COPYRIGHT)
        entries, header, problems = L.read_locale_file('deDE', L.catalogs()[0])
        self.assertEqual(problems, [])
        self.assertIn('Claude (AI-assisted, not yet reviewed by a native speaker; 5 strings)', header['translators'])
        self.assertEqual(header['humans'], [])
        xml = (self.root / 'locales.xml').read_text()
        self.assertLess(xml.index('deDE.lua'), xml.index('enUS.lua'))

    def test_the_result_is_a_fixed_point_of_rebuild(self):
        self.convert()
        before = {p.name: p.read_text() for p in (self.root / 'Locales').glob('*.lua')}
        L.Model()  # constructing the model reads the new layout
        import io
        import contextlib
        with contextlib.redirect_stdout(io.StringIO()):
            L.cmd_rebuild()
        self.assertEqual({p.name: p.read_text() for p in (self.root / 'Locales').glob('*.lua')}, before)


if __name__ == '__main__':
    unittest.main()
