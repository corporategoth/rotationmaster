-- A new rotation that was never saved can be thrown away: Discard, the header
-- Delete, the leave prompt's Discard, or just moving on to another rotation
-- remove it from the list (it used to stay until a reload). A saved one still
-- deletes through its confirmation, and the fallback is never removed.
local F=dofile('tests/fixtures/addon.lua')
local function read(path) local h=assert(io.open(path));local text=h:read('*a');h:close();return text end
local prefix=assert(read('tests/rotation_scope_browser_ui.lua'):match('^(.-)\ntest%('))
local fixture,ref=assert(loadstring(prefix..'\nreturn fixture,ref','@rotation-new-discard-fixture'))()
local test,finish=F.suite()
local function pendingRows(browser) local n=0;for _,row in ipairs(browser.rows) do if row.pending and not row.fallback then n=n+1 end end return n end
local function open() local f,a,parent=fixture();local browser=a:CreateRotationBrowser(parent,{spec=0,id=ref('class')});return f,a,parent,browser end
local function edit(pane,name) pane.name:SetText(name);pane.name.scripts.OnTextChanged(pane.name,true) end
local function savedKey(browser) for _,row in ipairs(browser.rows) do if not row.pending and not row.fallback and row.kind=='custom' then return row.key end end end

test('Discard on a new rotation removes it from the list and selects the fallback',function()
    local _,a,_,browser=open()
    browser.newButton:Click();local key=browser.selected;assert(browser.pane.workspace.pending and pendingRows(browser)==1)
    assert(browser.pane.delete:IsEnabled(),'a new rotation has no way to be deleted')
    browser.pane.discard:Click()
    assert(pendingRows(browser)==0 and not browser.rowsByKey[key],'the discarded new rotation is still listed')
    assert(browser.selected~=key and not browser.pane.workspace.pending or browser.pane.workspace.fallback)
    assert(#a:ListPendingRotationDrafts(0)==0,'the draft is still registered')
    assert(not a:ResolveRotationReference(0,key),'the discarded key still resolves')
end)
test('an edited new rotation is removed by Discard too, with nothing to confirm',function()
    local _,_,_,browser=open();browser.newButton:Click();local pane=browser.pane;edit(pane,'Scratch')
    assert(pane:HasUnsavedChanges())
    pane.discard:Click();assert(pendingRows(browser)==0 and not (pane.leavePrompt and pane.leavePrompt.frame:IsShown()))
end)
test('the header Delete removes a new rotation without a confirmation',function()
    local _,_,_,browser=open();browser.newButton:Click();local pane=browser.pane;edit(pane,'Scratch')
    pane.delete:Click();assert(not (pane.deletePrompt and pane.deletePrompt.frame:IsShown()),'a never-saved rotation asked for confirmation')
    assert(pendingRows(browser)==0)
end)
test('switching away from an edited new rotation and choosing Discard removes it',function()
    local _,_,_,browser=open();local target=savedKey(browser);browser.newButton:Click();local pane=browser.pane;local key=browser.selected;edit(pane,'Scratch')
    browser:SelectRotation(0,target);assert(pane.leavePrompt.frame:IsShown() and browser.selected==key,'no leave prompt for an edited draft')
    pane.leavePrompt.discard:Click()
    assert(browser.selected==target and pendingRows(browser)==0 and not browser.rowsByKey[key],'Discard in the prompt left the placeholder')
end)
test('Cancel in the prompt keeps the draft; Apply saves it as a normal rotation',function()
    local _,_,_,browser=open();local target=savedKey(browser);browser.newButton:Click();local pane=browser.pane;local key=browser.selected;edit(pane,'Keeper')
    browser:SelectRotation(0,target);pane.leavePrompt.cancel:Click();assert(browser.selected==key and pendingRows(browser)==1)
    browser:SelectRotation(0,target);pane.leavePrompt.apply:Click()
    assert(browser.selected==target and pendingRows(browser)==0)
    local found;for _,row in ipairs(browser.rows) do if row.name=='Keeper' then found=row end end;assert(found and not found.pending,'the applied rotation is not listed')
end)
test('an untouched new rotation is dropped as soon as another rotation is chosen',function()
    local _,_,_,browser=open();local target=savedKey(browser);browser.newButton:Click();local key=browser.selected
    browser:SelectRotation(0,target)
    assert(browser.selected==target and pendingRows(browser)==0 and not browser.rowsByKey[key],'an untouched placeholder stayed in the list')
end)
test('closing the window keeps an edited new draft but drops an untouched one',function()
    local _,a,parent,browser=open();browser.newButton:Click();assert(pendingRows(browser)==1)
    browser:Release();assert(#a:ListPendingRotationDrafts(0)==0,'an untouched new rotation survived closing')
    browser=a:CreateRotationBrowser(parent,{spec=0,id=ref('class')});assert(pendingRows(browser)==0)
    browser.newButton:Click();edit(browser.pane,'Draft');browser:Release();assert(#a:ListPendingRotationDrafts(0)==1,'an edited draft was lost on closing')
end)
test('a rotation that was created and applied deletes through its confirmation',function()
    local _,_,_,browser=open();browser.newButton:Click();local pane=browser.pane;local key=browser.selected;edit(pane,'Made');pane:Apply()
    assert(not pane.workspace.pending and pane.delete:IsEnabled() and browser.rowsByKey[key])
    pane.delete:Click();assert(pane.deletePrompt.frame:IsShown(),'a saved rotation deleted without confirming')
    pane.deletePrompt.confirm:Click();assert(not browser.rowsByKey[key] and pendingRows(browser)==0)
end)
test('the fallback is never discarded or deleted',function()
    local _,a,_,browser=open();browser:SelectRotation(0,ref('class','Saved fallback'),true);local pane=browser.pane;assert(pane.workspace.fallback)
    assert(not pane.delete:IsEnabled() and not pane:DiscardNew() and not a:DiscardPendingRotation(pane.workspace))
    assert(not a:DiscardPendingRotation(pane.workspace) and pane.workspace:ValidTarget())
end)
finish()
