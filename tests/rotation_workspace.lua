local F=dofile('tests/fixtures/addon.lua')
local test,finish=F.suite()
local function body(name) return {name=name or 'Mine',switch={},rotation={{id='a',type='spell',action=403,conditions={}}},cooldowns={}} end
local function fixture()
    local a={db={profile={rotations={[0]={mine=body()}}}}}
    for _,file in ipairs({'Data/plain.lua','Data/rotation_tree.lua','Data/rotation_draft.lua','Data/validation.lua','Core/rotation_editor.lua'}) do assert(loadfile(file))('rotationmaster',a) end
    local file=io.open('Core/rotation_workspace.lua');if file then file:close();assert(loadfile('Core/rotation_workspace.lua'))('rotationmaster',a) end
    local n=0;function a.uuid() n=n+1;return 'new-'..n end
    function a:GetEditableRotation(spec,id) return self.db.profile.rotations[spec] and self.db.profile.rotations[spec][id] end
    function a:GetDefaultIdForRuntime(_,id) if id=='builtin' then return 'pack' end end
    function a:ListDefaultRotations() return {{id='pack',runtimeKey='builtin',name='Default',description='Leveling',enabled=true,envelope={body=body('Default')}}} end
    function a:GetImportValidationOptions() return {} end
    function a:validateCondition() return true end
    return a
end
test('the legacy fallback keeps its fixed name while allowing its first explicit save',function()
    local a=fixture();local env=setmetatable({DEFAULT='Fallback',NEW='New'},{__index=_G})
    local chunk=assert(loadfile('Core/rotation_workspace.lua'));setfenv(chunk,env);chunk('rotationmaster',a)
    local w=assert(a:GetRotationEditWorkspace(0,'Fallback'))
    assert(w.title=='Fallback' and w:Snapshot().name=='Fallback')
    assert(not w:Command('SetBodyField','name','Renamed'));assert(w:Apply())
    assert(a:GetEditableRotation(0,'Fallback').name=='Fallback')
end)
test('same live owner resumes a detached workspace and Apply resets history',function()
    local a=fixture();local w=assert(a:GetRotationEditWorkspace(0,'mine'))
    assert(w:Command('SetBodyField','name','Edited'));assert(a:GetEditableRotation(0,'mine').name=='Mine')
    assert(a:GetRotationEditWorkspace(0,'mine')==w and w:IsDirty())
    assert(w:Apply());assert(a:GetEditableRotation(0,'mine').name=='Edited' and not w:IsDirty() and not w.session:HistoryState().canUndo)
    assert(w:Command('SetBodyField','name','Abandoned'));assert(w:Discard());assert(w:Snapshot().name=='Edited')
end)
test('default and custom workspaces expose matching bodies but defaults cannot mutate',function()
    local a=fixture();local w=assert(a:GetRotationEditWorkspace(0,'builtin'))
    assert(w.readOnly and w.title=='Default' and w.description=='Leveling' and #w:Snapshot().rotation==1)
    assert(not w:Command('Remove','a') and not w:Apply() and not w:IsDirty())
    local target=assert(w:ConditionEditorTarget('a'));assert(target.readOnly and not target.commit({type='CHANGED'}))
    assert(next(w:Snapshot().rotation[1].conditions)==nil)
end)
test('profile or same-ID body replacement never receives an old draft',function()
    local a=fixture();local old=a.db.profile;local w=assert(a:GetRotationEditWorkspace(0,'mine'));assert(w:Command('SetBodyField','name','Unsaved'))
    old.rotations[0].mine=body('Replacement');assert(not w:Apply() and not w:ValidTarget())
    local replacement=assert(a:GetRotationEditWorkspace(0,'mine'));assert(replacement~=w and replacement:Snapshot().name=='Replacement')
    a.db.profile={rotations={[0]={mine=body('New profile')}}};assert(not replacement:ValidTarget())
    assert(a:GetRotationEditWorkspace(0,'mine')~=replacement and a:GetEditableRotation(0,'mine').name=='New profile')
end)
test('new rotations remain private until Apply and same-ID insertion blocks stale creation',function()
    local a=fixture();local w=assert(a:GetRotationEditWorkspace(0,'pending'))
    assert(w.pending and a:GetEditableRotation(0,'pending')==nil)
    assert(w:Command('SetBodyField','name','Created'));assert(w:Apply());assert(not w.pending and a:GetEditableRotation(0,'pending').name=='Created')
    assert(a:GetRotationEditWorkspace(0,'pending')==w)
    local another=assert(a:GetRotationEditWorkspace(0,'collision'));assert(another:Command('SetBodyField','name','Unsaved'))
    a.db.profile.rotations[0].collision=body('Other');assert(not another:Apply());assert(a:GetEditableRotation(0,'collision').name=='Other')
end)
test('nested condition commits are one history step and stale commits cannot overwrite edits',function()
    local a=fixture();local w=assert(a:GetRotationEditWorkspace(0,'mine'))
    local target=assert(w:ConditionEditorTarget('a'));target.condition.note='Edited'
    assert(target.valid() and target.commit(target.condition));assert(w:Snapshot().rotation[1].conditions.note=='Edited')
    assert(not target.commit({note='Second callback'}));assert(w.session:Undo());assert(next(w:Snapshot().rotation[1].conditions)==nil)
    target=assert(w:ConditionEditorTarget('a'));assert(w:Command('SetCondition','a',{note='Other edit'}))
    assert(not target.valid() and not target.commit({note='Stale'}));assert(w:Snapshot().rotation[1].conditions.note=='Other edit')
    target=assert(w:ConditionEditorTarget('a'));assert(w:Discard());assert(not target.valid() and not target.commit({note='Released session'}))
end)
test('condition ownership includes stable IDs deletion and rotation-switch identity',function()
    local a=fixture();local w=assert(a:GetRotationEditWorkspace(0,'mine'))
    local target=assert(w:ConditionEditorTarget('a'));assert(w:Command('Remove','a'));assert(not target.valid() and not target.commit({}))
    local switch=assert(w:ConditionEditorTarget({kind='switch'}));assert(switch.commit({disabled=true}));assert(w:Snapshot().switch.disabled)
    assert(a:GetEditableRotation(0,'mine').switch.disabled==nil)
end)
test('new rotation needs a usable name before any SavedVariables entry is created',function()
    local a=fixture();local w=assert(a:GetRotationEditWorkspace(0,'pending'))
    assert(not w:Apply() and a:GetEditableRotation(0,'pending')==nil)
    assert(w:Command('SetBodyField','name','  '));assert(not w:Apply())
    assert(w:Command('SetBodyField','name','Named'));assert(w:Apply())
end)
test('separate description and metadata stay detached undoable and persisted',function()
    local a=fixture();local w=assert(a:GetRotationEditWorkspace(0,'mine'))
    assert(w:Command('SetBodyField','description','Leveling with shields'))
    assert(w:Command('SetBodyField','metadata',{author='PreZ'}));assert(a:GetEditableRotation(0,'mine').description==nil)
    assert(w.session:Undo());assert(w:Snapshot().metadata==nil);assert(w.session:Redo());assert(w:Apply())
    assert(a:GetEditableRotation(0,'mine').description=='Leveling with shields' and a:GetEditableRotation(0,'mine').metadata.author=='PreZ')
end)
finish()
