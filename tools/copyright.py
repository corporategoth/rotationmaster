"""The copyright notice at the top of every original source file, and the licence field of every TOC.

  python3 tools/copyright.py --check     list every file that lacks the notice, carries an older one or is not classified
  python3 tools/copyright.py --write     put the notice (or this text of it) at the top of every file that needs it
  python3 tools/copyright.py --list      how many files each kind holds, and which are skipped and why

The full terms live only in LICENSE; a file carries one line that names the owner and points there. That line is written in
the file's own comment syntax and is the first line (after a shebang, or after the XML declaration). `--write` is idempotent
and upgrades an older notice (another year, older wording) in place.

Every tracked file must be classified below: written with a comment syntax (`INCLUDE`) or skipped with a reason (`SKIP`).
A file of a kind nobody has classified fails the check with "not classified", so a new extension forces a decision rather
than silently going without a notice. The years and the licence wording are the constants below and nowhere else:
tools/locales.py (the TOC it writes), tools/generate_artwork_catalog.py (.pkgmeta) and tools/generate_builtin_sources.py
(Data/builtin_sources.lua) import them.

Every TOC also carries `## X-License: MIT + Attribution` (the in-game About page shows that field); the check enforces it.
"""
import argparse
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]

# ---------------------------------------------------------------------------------------------------------------------
# The one place the years and the wording live.
# ---------------------------------------------------------------------------------------------------------------------
FIRST_YEAR = 2018
LAST_YEAR = 2026
OWNER = 'Preston A. Elder <prez@neuromancy.net>'
LICENSE_SUMMARY = 'a modified MIT license (MIT + Attribution)'
LICENSE_FILE = 'LICENSE'
NOTICE = f'Copyright {FIRST_YEAR}-{LAST_YEAR} {OWNER}. Released under {LICENSE_SUMMARY}; see the {LICENSE_FILE} file for details.'
# The value of `## X-License:` in every TOC (the About page shows it).
TOC_LICENSE = 'MIT + Attribution'
TOC_LICENSE_FIELD = f'## X-License: {TOC_LICENSE}'

# ---------------------------------------------------------------------------------------------------------------------
# Comment syntaxes. `blank` is whether `--write` puts an empty line after the notice (the file's own header follows it).
# ---------------------------------------------------------------------------------------------------------------------
KINDS = {
    'lua': {'prefix': '-- ', 'suffix': '', 'blank': True},
    'python': {'prefix': '# ', 'suffix': '', 'blank': True, 'shebang': True},
    'shell': {'prefix': '# ', 'suffix': '', 'blank': True, 'shebang': True},
    'yaml': {'prefix': '# ', 'suffix': '', 'blank': True},
    # A TOC comment is a line that starts with a single `#` (`##` starts a field); it may sit before `## Interface:`.
    'toc': {'prefix': '# ', 'suffix': '', 'blank': False},
    # An XML comment never goes before the declaration.
    'xml': {'prefix': '<!-- ', 'suffix': ' -->', 'blank': False, 'declaration': True},
}
XML_DECLARATION = re.compile(r'^<\?xml\b.*\?>\s*$')

# ---------------------------------------------------------------------------------------------------------------------
# Classification. The first rule that matches a tracked path decides. Order matters: the exceptions come first.
# ---------------------------------------------------------------------------------------------------------------------
# (regular expression on the repository-relative path, 'include' kind or 'skip' reason)
RULES = [
    # --- vendored: their own licences, their pinned bytes ---------------------------------------------------------------
    (r'^Libs/', ('skip', 'vendored library: keeps its own licence (Libs/UPSTREAM.json pins its bytes)')),
    (r'^LibsAugment/', ('skip', 'vendored library augmentation: keeps its own licence')),
    (r'^tools/vendor/', ('skip', 'vendored tool (BigWigs packager): keeps its own licence')),
    # --- generated: the generator is the author -------------------------------------------------------------------------
    (r'^Locales/[A-Za-z]+\.lua$', ('skip', 'generated by tools/locales.py (the generator, not this checker, owns its first line)')),
    (r'^Modules/RotationMaster_[A-Za-z]+Text/[A-Za-z]+\.lua$',
     ('skip', 'text bundle locale tables, generated by tools/locales.py (the generator owns its first line)')),
    (r'^Data/text_bundle_index\.lua$', ('skip', 'generated by tools/locales.py index; the generator owns its first line')),
    (r'^Data/artwork\.lua$', ('skip', 'generated by tools/generate_artwork_catalog.py; its header names the generator')),
    (r'^tests/fixtures/client_api_[a-z]+\.lua$',
     ('skip', 'generated by tools/generate_client_api.py from the clients\' own data')),
    # --- art, fonts and textures; Python that exports the art is source -------------------------------------------------
    (r'^Assets/.*\.py$', ('include', 'python')),
    (r'^Assets/', ('skip', 'art, its provenance records and notes: not source')),
    (r'^Fonts/', ('skip', 'font and its licence')),
    (r'^textures/', ('skip', 'texture')),
    # --- by name --------------------------------------------------------------------------------------------------------
    (r'^\.pkgmeta$', ('include', 'yaml')),
    (r'^tools/check$', ('include', 'python')),
    (r'(^|/)LICENSE$', ('skip', 'licence text')),
    (r'^\.gitignore$', ('skip', 'git configuration, not source')),
    (r'^\.gitattributes$', ('skip', 'git configuration, not source')),
    # --- by extension ---------------------------------------------------------------------------------------------------
    (r'\.lua$', ('include', 'lua')),
    (r'\.py$', ('include', 'python')),
    (r'\.sh$', ('include', 'shell')),
    (r'\.ya?ml$', ('include', 'yaml')),
    (r'\.toc$', ('include', 'toc')),
    (r'\.xml$', ('include', 'xml')),
    (r'\.json$', ('skip', 'JSON has no comment syntax')),
    (r'\.(md|txt|textile)$', ('skip', 'prose and lists, not source')),
    (r'\.(svg|tga|png|blp|ttf)$', ('skip', 'image or font')),
]
COMPILED = [(re.compile(pattern), action) for pattern, action in RULES]

# Files that are source-like and ours but must keep their exact bytes (a test reads them as text, or they are frozen
# oracles/snapshots). Each entry is an exact path and must exist; the reason names what depends on the bytes.
FROZEN = {}

STALE = re.compile(r'^(?:-- |# |<!-- )Copyright \d{4}(?:-\d{4})?\b.*Elder\b')


def classify(path):
    """('include', kind), ('skip', reason) or None for a path no rule covers."""
    if path in FROZEN:
        return ('skip', FROZEN[path])
    for pattern, action in COMPILED:
        if pattern.search(path):
            return action
    return None


def notice_line(kind):
    syntax = KINDS[kind]
    return syntax['prefix'] + NOTICE + syntax['suffix']


def notice_index(kind, lines):
    """The index of the line the notice belongs on: after a shebang, or after the XML declaration."""
    syntax = KINDS[kind]
    if syntax.get('shebang') and lines and lines[0].startswith('#!'):
        return 1
    if syntax.get('declaration') and lines and XML_DECLARATION.match(lines[0]):
        return 1
    return 0


def problem(kind, text):
    """None when the notice is in place, else why not: 'missing notice', 'stale notice' or 'misplaced notice'."""
    lines = text.split('\n')
    index = notice_index(kind, lines)
    want = notice_line(kind)
    here = lines[index] if index < len(lines) else ''
    if here == want:
        return None
    if STALE.match(here):
        return 'stale notice'
    if want in lines:
        return 'misplaced notice'
    return 'missing notice'


def fixed(kind, text):
    """The text with the notice in place (unchanged when it already is); None when a misplaced notice needs a human."""
    why = problem(kind, text)
    if why is None:
        return text
    if why == 'misplaced notice':
        return None
    lines = text.split('\n')
    index = notice_index(kind, lines)
    want = notice_line(kind)
    if why == 'stale notice':
        lines[index] = want
        return '\n'.join(lines)
    syntax = KINDS[kind]
    head = '\n'.join(lines[:index]) + '\n' if index else ''
    rest = '\n'.join(lines[index:])
    if not rest:
        return head + want + '\n'
    separator = '\n\n' if syntax['blank'] and not rest.startswith('\n') else '\n'
    return head + want + separator + rest


def toc_problem(text):
    fields = [line for line in text.split('\n') if line.startswith('## X-License:')]
    if fields != [TOC_LICENSE_FIELD]:
        return f'TOC licence field must be exactly "{TOC_LICENSE_FIELD}"'
    return None


def tracked(root=ROOT):
    out = subprocess.run(['git', '-C', str(root), 'ls-files', '-z'], capture_output=True, check=True).stdout
    return sorted(name for name in out.decode('utf-8').split('\0') if name and (Path(root) / name).is_file())


def survey(root=ROOT, names=None):
    """(problems, counts, skipped): problems are (path, why); counts maps kind to files; skipped maps path to reason."""
    everything = names is None
    names = tracked(root) if everything else names
    problems, counts, skipped = [], {}, {}
    for name in names:
        action = classify(name)
        if action is None:
            problems.append((name, 'not classified (add a rule to RULES in tools/copyright.py: include with a comment syntax, or skip with a reason)'))
        elif action[0] == 'skip':
            skipped[name] = action[1]
        else:
            kind = action[1]
            counts[kind] = counts.get(kind, 0) + 1
            try:
                text = (Path(root) / name).read_text(encoding='utf-8')
            except (OSError, UnicodeDecodeError) as error:
                problems.append((name, f'unreadable: {error}'))
                continue
            why = problem(kind, text)
            if why:
                problems.append((name, why))
            if kind == 'toc':
                why = toc_problem(text)
                if why:
                    problems.append((name, why))
    if everything:
        for name in FROZEN:
            if name not in names:
                problems.append((name, 'FROZEN entry names a file that is not tracked'))
    return problems, counts, skipped


def check(root=ROOT, names=None):
    """The problems as (path, why) pairs; empty when every file is in order."""
    return survey(root, names)[0]


def write(root=ROOT, names=None):
    """Put the notice in every included file that needs it; returns (changed paths, problems that need a human)."""
    changed, stuck = [], []
    for name in tracked(root) if names is None else names:
        action = classify(name)
        if action is None or action[0] == 'skip':
            continue
        path = Path(root) / name
        text = path.read_text(encoding='utf-8')
        new = fixed(action[1], text)
        if new is None:
            stuck.append((name, 'misplaced notice: move or delete it by hand'))
        elif new != text:
            path.write_text(new, encoding='utf-8')
            changed.append(name)
    return changed, stuck


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--check', action='store_true', help='report files without the notice (the default)')
    mode.add_argument('--write', action='store_true', help='add or upgrade the notice')
    mode.add_argument('--list', action='store_true', help='counts per kind and the skipped files with their reasons')
    args = parser.parse_args()
    if args.write:
        changed, stuck = write()
        for name, why in stuck:
            print(f'{name}: {why}')
        print(f'{len(changed)} file(s) updated')
        return 1 if stuck else 0
    problems, counts, skipped = survey()
    if args.list:
        for kind in sorted(counts):
            print(f'{kind:8} {counts[kind]}')
        reasons = {}
        for name, reason in skipped.items():
            reasons.setdefault(reason, []).append(name)
        for reason, files in sorted(reasons.items(), key=lambda item: -len(item[1])):
            print(f'skip {len(files):4}  {reason}')
        return 0
    for name, why in problems:
        print(f'{name}: {why}')
    if problems:
        print(f'{len(problems)} problem(s); python3 tools/copyright.py --write fixes a missing or stale notice', file=sys.stderr)
        return 1
    print(f'Copyright notice: {sum(counts.values())} files carry it, {len(skipped)} skipped by rule')
    return 0


if __name__ == '__main__':
    sys.exit(main())
