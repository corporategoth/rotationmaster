#!/usr/bin/env python3
"""Compile the reviewed artwork manifests into a small runtime catalog."""
import argparse
import fnmatch
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import package_release as P  # noqa: E402
OVERLAY_LABELS = {
    'arcane-ring': 'Arcane Ring', 'ember-corners': 'Ember Corners',
    'frost-shards': 'Frost Shards', 'nature-vines': 'Nature Vines',
    'lightning-sweep': 'Lightning Sweep', 'holy-rays': 'Holy Rays',
    'shadow-claws': 'Shadow Claws', 'rune-diamond': 'Rune Diamond',
    'arcane-ring-neutral': 'Neutral Arcane Ring',
}
CATEGORY_LABELS = {'category-combat': 'Combat', 'category-character': 'Character',
                   'category-spells': 'Spells', 'category-items': 'Items',
                   'category-buffs': 'Buffs', 'category-spatial': 'Spatial',
                   'category-all': 'All', 'category-switch': 'Switch', 'category-other': 'Other'}
SPECIAL_CATEGORIES = {'category-all': 'ALL', 'category-switch': 'SWITCH', 'category-other': 'DEFAULT'}


def quote(value):
    return json.dumps(value, ensure_ascii=False)


def generate():
    icons = json.loads((ROOT / 'Assets/Conditions/v2/provenance.json').read_text())['entries']
    overlays = json.loads((ROOT / 'Assets/Overlays/v1/provenance.json').read_text())['entries']
    assert len(icons) == 153 and len(overlays) == 9
    lines = ['-- Generated by tools/generate_artwork_catalog.py; selected manifests are authoritative.',
             'local addon_name,addon=...', "local L=LibStub('AceLocale-3.0'):GetLocale(addon_name)",
             "local root='Interface\\\\AddOns\\\\'..addon_name..'\\\\'",
             'local artwork={condition={},logic={},category={},icons={},overlays={}}', 'addon.Artwork=artwork']
    selected = set()
    for entry in icons + overlays:
        runtime = entry['runtime']
        assert entry['status'] == 'generated' and runtime not in selected
        assert runtime == f"Assets/{'Overlays/v1' if entry['kind'] == 'overlay' else 'Conditions/v2'}/{entry['name']}.tga"
        assert (ROOT / runtime).is_file()
        selected.add(runtime)
        path = 'root..' + quote(runtime[:-4].replace('/', '\\'))
        if entry['kind'] == 'overlay':
            lines.append('artwork.overlays[#artwork.overlays+1]={key=' + quote(entry['key']) + ',value=' + path + ',icon=' + path + ',text=L[' + quote(OVERLAY_LABELS[entry['key']]) + ']}')
        else:
            kind = entry['kind']
            key = SPECIAL_CATEGORIES.get(entry['key'], entry.get('category_id', entry['key']))
            lines.append('artwork.' + kind + '[' + quote(key) + ']=' + path)
            caption = CATEGORY_LABELS[entry['key']] if kind == 'category' else entry.get('description', entry['key'])
            lines.append('artwork.icons[#artwork.icons+1]={texture=artwork.' + kind + '[' + quote(key) + '],name=L[' + quote(caption) + ']}')
    return '\n'.join(lines) + '\n'


def release_metadata():
    # The package holds what the game client loads, plus license and notice files. Everything else stays in Git:
    # development trees, art sources and their QA, scripts, and data files the client cannot read.
    # The packager already skips every dotfile; naming the development trees here keeps the intent in the file and lets
    # tools/package_release.py --check state it as a rule.
    ignored = ['tests', 'tools', 'docs', '.claude', '.gitea', '.github', '.pre-commit-config.yaml', '.gitattributes',
               'README.md', 'CONTRIBUTING.md', 'CHANGELOG.md',
               'Modules/README.md',
               'Data/talent_trees.json',
               'Assets/Conditions/source', 'Assets/Conditions/qa',
               'Assets/Conditions/v2/source', 'Assets/Conditions/v2/qa',
               'Assets/Overlays/v1/source', 'Assets/Overlays/v1/qa',
               # Notes, manifests, exporters and picture sources of the art; the client reads only .tga and .blp.
               'Assets/*.md', 'Assets/*.json', 'Assets/*.py', 'Assets/*.png', 'Assets/*.svg',
               # Vendored libraries: their readmes and the pin manifests (their LICENSE files stay).
               'Libs/*/README.*', 'Libs/*.json',
               'Locales/*.json']
    # Then what is in the repository for the tools but not for the game: code no TOC or XML loads, and textures and
    # fonts that no loaded code names (the 64 and 128 px companions, superseded art, controls nothing uses).
    tracked = [name for name in P.tracked_files(ROOT) if not name.startswith('.')]
    globs = P.ignore_globs(ROOT, ignored)
    kept = [name for name in tracked if not any(fnmatch.fnmatchcase(name, glob) for glob in globs)]
    texts = {name: (ROOT / name).read_text(encoding='utf-8') for name in kept if name.endswith(P.CODE_SUFFIXES + ('.toc',))}
    texts['Data/artwork.lua'] = generate()
    unloaded, unnamed = P.unused_files(kept, texts.__getitem__)
    ignored.extend(unloaded + unnamed)
    # Each load-on-demand Built In module (Modules/<Addon>/) leaves the zip as
    # its own top-level AddOns folder beside RotationMaster.
    modules = sorted(path.name for path in (ROOT / 'Modules').iterdir()
                     if path.is_dir() and any(path.glob('*.toc')))
    return ('# Generated by tools/generate_artwork_catalog.py. Originals remain in Git.\n'
            '# The package holds what the game loads, and the license and notice files.\n'
            'package-as: RotationMaster\n'
            # CI writes this file from tools/release_notes.py before the packager runs; it is not tracked.
            # Indented four spaces so tests/verify.py does not read it as a move-folders line.
            'manual-changelog:\n'
            '    filename: CHANGELOG.md\n'
            '    markup-type: markdown\n'
            'move-folders:\n' + ''.join(f'  RotationMaster/Modules/{name}: {name}\n' for name in modules) +
            'ignore:\n' + ''.join('  - ' + path + '\n' for path in ignored))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for target, content in [(ROOT / 'Data/artwork.lua', generate()), (ROOT / '.pkgmeta', release_metadata())]:
        if args.write:
            target.write_text(content)
        elif not target.exists() or target.read_text() != content:
            raise SystemExit(f'{target.name} is stale; run python3 tools/generate_artwork_catalog.py --write')
    print('Selected artwork catalog: 153 icons, 9 overlays; current')


if __name__ == '__main__':
    main()
