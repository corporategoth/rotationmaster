#!/usr/bin/env python3
"""Write Web/site/conditions.json: condition type names and default categories.

The website's Conditions reference and its condition-category share pages read
this file. It is generated from the addon's own registrations (the English
`description` label of each RegisterCondition call), the default category
lists and default switch list in init.lua, and the reviewed declarative catalog
Web/schema/catalog.json for the authoritative set of condition identifiers.
Nothing is executed; the Lua sources are read as text.

Run from anywhere:  python3 tools/export_web_conditions.py
Check only:         python3 tools/export_web_conditions.py --check
"""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'Web/site/conditions.json'


def lua_list(text, name):
    match = re.search(r'local\s+' + re.escape(name) + r'\s*=\s*\{(.*?)\n\}', text, re.S)
    if not match:
        raise SystemExit(f'init.lua: {name} not found')
    return match.group(1)


def strings(block):
    return re.findall(r'"([A-Z0-9_]+)"', block)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true', help='fail if the committed file is stale')
    args = parser.parse_args()

    catalog = json.loads((ROOT / 'Web/schema/catalog.json').read_text(encoding='utf-8'))
    ids = sorted(c['id'] for c in catalog['conditions'])
    modules = {c['id']: c['module'] for c in catalog['conditions']}

    names = {}
    for path in sorted((ROOT / 'Conditions').glob('*.lua')):
        text = path.read_text(encoding='utf-8')
        pattern = r'(?:RegisterCondition\(\s*|delayed_condition\[[^\]]+\]\[\s*)["\']([A-Z0-9_]+)["\']'
        for match in re.finditer(pattern, text):
            tail = text[match.end():match.end() + 700]
            label = re.search(r'description\s*=\s*L\[["\']([^"\']+)["\']\]', tail)
            if label:
                names.setdefault(match.group(1), label.group(1))

    init = (ROOT / 'init.lua').read_text(encoding='utf-8')
    groups_block = lua_list(init, 'default_condition_groups')
    groups = []
    for match in re.finditer(r'id\s*=\s*"([0-9a-f-]+)",\s*name\s*=\s*L\["([^"]+)"\],\s*conditions\s*=\s*\{(.*?)\}', groups_block, re.S):
        groups.append({'id': match.group(1), 'name': match.group(2),
                       'conditions': [c for c in strings(match.group(3)) if c in modules]})
    switch = [c for c in strings(lua_list(init, 'default_switch_conditions')) if c in modules]
    switch_only = [c for c in strings(lua_list(init, 'default_disabled_conditions')) if c in modules]

    # New profiles are also seeded by cold initializers that append to the
    # Character / Spells categories and the switch list (see init.lua and
    # Core/unit_state_conditions.lua). Mirror those appends.
    by_id = {g['id']: g for g in groups}
    seeders = [init, (ROOT / 'Core/unit_state_conditions.lua').read_text(encoding='utf-8')]
    for text in seeders:
        for body in re.findall(r'function addon:Initialize\w+Conditions\(.*?\nend', text, re.S):
            tags = re.search(r"ipairs\(\{([^}]*)\}\)", body)
            seeded = [t for t in re.findall(r"'([A-Z0-9_]+)'", tags.group(1))] if tags else []
            if 'append(profile.switch_conditions)' in body:
                switch += [t for t in seeded if t in modules and t not in switch]
            for gid in re.findall(r"category\.id=='([0-9a-f-]+)' then append", body):
                if gid in by_id:
                    by_id[gid]['conditions'] += [t for t in seeded if t in modules and t not in by_id[gid]['conditions']]
            for gid, tag in re.findall(r"category\.id=='([0-9a-f-]+)' and not [^\n]*?'([A-Z0-9_]+)'\) then", body):
                if gid in by_id and tag in modules and tag not in by_id[gid]['conditions']:
                    by_id[gid]['conditions'].append(tag)
    for g in groups:
        del g['id']

    grouped = {c for g in groups for c in g['conditions']}
    other = [c for c in ids if c not in grouped]
    if other:
        groups.append({'name': 'Other', 'conditions': other})

    missing = [c for c in ids if c not in names]
    if missing:
        raise SystemExit('No English label found for: ' + ', '.join(missing))

    document = {
        'format': 'RotationMasterWebConditionNames',
        'version': 1,
        'note': 'Generated by tools/export_web_conditions.py from Conditions/*.lua, init.lua and Web/schema/catalog.json.',
        'logical': {'AND': 'All of (AND)', 'OR': 'Any of (OR)', 'NOT': 'Not'},
        'conditions': {c: {'name': names[c], 'module': modules[c]} for c in ids},
        'groups': groups,
        'switchDefaults': switch,
        'switchOnly': switch_only,
    }
    output = json.dumps(document, indent=1, ensure_ascii=False, sort_keys=False) + '\n'
    if args.check:
        current = TARGET.read_text(encoding='utf-8') if TARGET.exists() else ''
        if current != output:
            print(f'{TARGET.relative_to(ROOT)} is stale; run python3 tools/export_web_conditions.py', file=sys.stderr)
            return 1
        print('Web condition names: current')
        return 0
    TARGET.write_text(output, encoding='utf-8')
    print(f'Wrote {TARGET.relative_to(ROOT)}: {len(ids)} conditions in {len(groups)} groups')
    return 0


if __name__ == '__main__':
    sys.exit(main())
