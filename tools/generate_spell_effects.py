"""Generate Data/spell_effects_<family>.lua: what casting a class spell leaves behind, from the game's own spell tables.

  python3 tools/generate_spell_effects.py --family forever --fetch   download the tables, then write the file
  python3 tools/generate_spell_effects.py --family forever           write it from the tables already downloaded
  python3 tools/generate_spell_effects.py --check                    offline: every generated file is what it says it is

The forecast (Core/forecast.lua) predicts the recommendations after the first by assuming the earlier ones were cast. What a
cast leaves (a debuff on the target, a buff on the player, for how long) is hidden from the addon on restricted clients, so it
is read here, once, from the public DB2 tables (wago.tools) and shipped as data. Only spells a class can learn are kept, and only
those that apply an aura, directly or through the spell they trigger.

Normal checks never download: --fetch is the only thing that touches the network. The tables are cached under
.tools/spell-data/<product>-<build>/ (not tracked). The generated file records the build and a SHA-256 of its rows; --check
proves nobody edited the rows by hand. Rows: `spell=entry,entry,...` joined by `;`, an entry being
  `t:aura:seconds[:stacks]` or `p:aura:seconds[:stacks]`  an aura left on the target or the player (seconds is 0 until removed;
                                                          stacks is the most it stacks to, left out when it does not stack),
  `g:type:n`                                              n points of a point resource (combo points, holy power, ...) gained,
  `f:type`                                                a finisher: it spends every point of that resource,
  `h:1`                                                   harmful: an effect of it is aimed at an enemy (casting it starts combat).
A finisher is a class spell whose effect or whose duration grows with the points spent. A spell's own application
of an aura is always taken as certain: the chance in SpellAuraOptions is the rate of a proc, which these tables do not tie to
a cast, so no chance is guessed from it.
"""
import argparse
import csv
import hashlib
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / '.tools' / 'spell-data'
API = 'https://wago.tools'
FAMILIES = {'forever': 'wowf', 'retail': 'wow'}
TABLES = ['SpellEffect', 'SpellMisc', 'SpellDuration', 'SpellAuraOptions', 'SkillLineAbility']
EXTRA = {'retail': ['TraitDefinition', 'SpecializationSpells']}
HEADER = '-- GENERATED by tools/generate_spell_effects.py; do not edit by hand.'

# Effect types that apply an aura, and the one that casts another spell.
APPLY = {6: None, 35: 'p', 65: 'p', 128: 'p', 129: 't'}
TRIGGER = 64
# Implicit targets (the game's own numbers): who receives the aura.
ENEMY = {6, 15, 16, 24, 53}
CASTER = {1, 18, 20, 22, 56}
FRIEND = {21, 25, 57}
PASSIVE = 0x40
# Energize (an effect that gives a resource) and the power types that are counted in whole points: combo points, soul shards,
# holy power, chi, arcane charges and essence.
ENERGIZE = 30
POINT_TYPES = {4, 7, 9, 12, 16, 19}
COMBO_POINTS = 4


def unit_for(target_a, target_b):
    """'t' or 'p' for a pair of implicit targets; None when they say nothing the forecast can use."""
    pair = {target_a, target_b} - {0}
    if pair & ENEMY:
        return 't'
    if pair & CASTER:
        return 'p'
    if pair & FRIEND:
        return 't'
    return None


def get(url):
    # The site refuses the default Python client name.
    return urllib.request.Request(url, headers={'User-Agent': 'rotationmaster-tools (spell data generator)'})


def fetch(product, build, directory):
    directory.mkdir(parents=True, exist_ok=True)
    for table in TABLES + EXTRA.get(FAMILY_OF[product], []):
        url = f'{API}/db2/{table}/csv?build={build}'
        with urllib.request.urlopen(get(url), timeout=600) as response:
            (directory / f'{table}.csv').write_bytes(response.read())
        print(f'fetched {table}', file=sys.stderr)


def latest_build(product):
    with urllib.request.urlopen(get(f'{API}/api/builds'), timeout=60) as response:
        return json.load(response)[product][0]['version']


def table(directory, name):
    with open(directory / f'{name}.csv', encoding='utf-8', newline='') as handle:
        return list(csv.DictReader(handle))


def integer(value):
    try:
        return int(float(value))
    except (TypeError, ValueError):
        return 0


def referenced(family):
    """Every number of three or more digits in the family's Built In rotations: the spells the preview will be asked about.

    A superset on purpose (a threshold such as 100 is picked up too); the tables decide which of them are spells that apply an
    aura, so the extras cost nothing."""
    out = set()
    for path in (ROOT / 'Modules').glob(f'*/{family}/*.lua'):
        out |= {int(n) for n in re.findall(r'(?<![\w.])(\d{3,8})(?![\w.])', path.read_text(encoding='utf-8'))}
    return out


def build_rows(directory, family):
    effects = {}
    for row in table(directory, 'SpellEffect'):
        if integer(row['DifficultyID']) in (0,):
            effects.setdefault(integer(row['SpellID']), []).append(row)

    misc = {}
    for row in table(directory, 'SpellMisc'):
        if integer(row['DifficultyID']) == 0:
            misc[integer(row['SpellID'])] = row

    durations = {integer(row['ID']): integer(row['Duration']) for row in table(directory, 'SpellDuration')}
    per_point = {integer(row['ID']) for row in table(directory, 'SpellDuration') if integer(row['DurationPerResource'])}
    stacking = {}
    for row in table(directory, 'SpellAuraOptions'):
        if integer(row['DifficultyID']) == 0 and integer(row['CumulativeAura']) > 1:
            stacking[integer(row['SpellID'])] = integer(row['CumulativeAura'])
    spells = {integer(row['Spell']) for row in table(directory, 'SkillLineAbility') if integer(row['ClassMask']) != 0}
    if family == 'retail':
        spells |= {integer(row['SpellID']) for row in table(directory, 'TraitDefinition') if integer(row['SpellID'])}
        spells |= {integer(row['SpellID']) for row in table(directory, 'SpecializationSpells')}
    class_spells = set(spells)
    spells |= referenced(family)
    spells.discard(0)

    def seconds(spell):
        row = misc.get(spell)
        milliseconds = durations.get(integer(row['DurationIndex'])) if row else None
        return max(0, milliseconds // 1000) if milliseconds and milliseconds > 0 else 0

    def stacks(spell):
        return stacking.get(spell)

    def auras(spell, unit_hint):
        """The (unit, aura, seconds) an aura spell's own effects apply."""
        out = []
        for effect in effects.get(spell, []):
            kind = integer(effect['Effect'])
            if kind in APPLY and integer(effect['EffectAura']) != 0:
                unit = APPLY[kind] or unit_hint or unit_for(
                    integer(effect['ImplicitTarget_0']), integer(effect['ImplicitTarget_1'])
                )
                if unit:
                    out.append((unit, spell, seconds(spell), stacks(spell)))
        return out

    rows = {}
    for spell in sorted(spells):
        row = misc.get(spell)
        if row is None or integer(row['Attributes_0']) & PASSIVE:
            continue
        found = []
        for effect in effects.get(spell, []):
            kind = integer(effect['Effect'])
            if kind in APPLY and integer(effect['EffectAura']) != 0:
                unit = APPLY[kind] or unit_for(integer(effect['ImplicitTarget_0']), integer(effect['ImplicitTarget_1']))
                if unit:
                    found.append((unit, spell, seconds(spell), stacks(spell)))
            elif kind == ENERGIZE and integer(effect['EffectMiscValue_0']) in POINT_TYPES:
                found.append(('g', integer(effect['EffectMiscValue_0']), max(1, integer(effect['EffectBasePointsF'])), None))
            elif kind == TRIGGER and integer(effect['EffectTriggerSpell']):
                hint = unit_for(integer(effect['ImplicitTarget_0']), integer(effect['ImplicitTarget_1']))
                found.extend(auras(integer(effect['EffectTriggerSpell']), hint))
        if any(
            integer(effect['ImplicitTarget_0']) in ENEMY or integer(effect['ImplicitTarget_1']) in ENEMY
            for effect in effects.get(spell, [])
        ):
            found.append(('h', 1, 0, None))
        grows = any(integer(effect['EffectPointsPerResource']) for effect in effects.get(spell, [])) or (
            integer(row['DurationIndex']) in per_point
        )
        if grows and spell in class_spells:
            found.append(('f', COMBO_POINTS, 0, None))
        unique = []
        for item in found:
            if item not in unique:
                unique.append(item)
        if unique:
            rows[spell] = unique
    return rows


def encode(rows):
    parts = []
    for spell in sorted(rows):
        entries = []
        for unit, aura, length, many in rows[spell]:
            if unit == 'g':
                entries.append(f'g:{aura}:{length}')
            elif unit == 'f':
                entries.append(f'f:{aura}')
            elif unit == 'h':
                entries.append('h:1')
            else:
                entries.append(f'{unit}:{aura}:{length}' + (f':{many}' if many else ''))
        parts.append(f'{spell}=' + ','.join(entries))
    return ';'.join(parts)


def render(family, product, build, body):
    digest = hashlib.sha256(body.encode()).hexdigest()
    return (
        '-- Copyright 2018-2026 Preston A. Elder <prez@neuromancy.net>. Released under a modified MIT license (MIT + Attribution); see the LICENSE file for details.\n'
        '\n'
        f'{HEADER}\n'
        f'-- What a class spell leaves behind on the {family} client, from the game\'s spell tables ({product} {build}).\n'
        '-- Read lazily by Core/forecast.lua; see docs/architecture/forecast.md and tools/generate_spell_effects.py.\n'
        '\n'
        'local _, addon = ...\n'
        'local platform = addon.Platform\n'
        '\n'
        f"if not (platform and platform.GetClientFamily and platform:GetClientFamily() == '{family}') then\n"
        '    return\n'
        'end\n'
        '\n'
        'addon.SpellEffectData = addon.SpellEffectData or {}\n'
        f"addon.SpellEffectData['{family}'] = {{\n"
        f"    build = '{build}',\n"
        f"    hash = '{digest}',\n"
        f'    rows = "{body}",\n'
        '}\n'
    )


def target(family):
    return ROOT / 'Data' / f'spell_effects_{family}.lua'


def check():
    bad = 0
    found = False
    for family in FAMILIES:
        path = target(family)
        if not path.exists():
            continue
        found = True
        text = path.read_text(encoding='utf-8')
        body = re.search(r'rows = "([^"]*)"', text)
        digest = re.search(r"hash = '([0-9a-f]{64})'", text)
        if not body or not digest or hashlib.sha256(body.group(1).encode()).hexdigest() != digest.group(1):
            print(f'{path.relative_to(ROOT)}: rows do not match their recorded hash; regenerate, never edit', file=sys.stderr)
            bad += 1
        elif HEADER not in text:
            print(f'{path.relative_to(ROOT)}: generated header missing', file=sys.stderr)
            bad += 1
    if not found:
        print('no spell effect data files', file=sys.stderr)
    return 1 if bad else 0


FAMILY_OF = {product: family for family, product in FAMILIES.items()}


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--family', choices=sorted(FAMILIES))
    parser.add_argument('--build', help='the build to use (default: the newest wago.tools lists for the product)')
    parser.add_argument('--fetch', action='store_true', help='download the tables first (the only network use)')
    parser.add_argument('--check', action='store_true', help='offline: verify the generated files')
    args = parser.parse_args(argv)

    if args.check:
        return check()
    if not args.family:
        parser.error('--family is required')

    product = FAMILIES[args.family]
    build = args.build
    if not build:
        if not args.fetch:
            cached = sorted(CACHE.glob(f'{product}-*'))
            if not cached:
                raise SystemExit(f'no cached {product} tables; run with --fetch')
            build = cached[-1].name.split('-', 1)[1]
        else:
            build = latest_build(product)

    directory = CACHE / f'{product}-{build}'
    if args.fetch:
        fetch(product, build, directory)
    rows = build_rows(directory, args.family)
    path = target(args.family)
    path.write_text(render(args.family, product, build, encode(rows)), encoding='utf-8')
    print(f'{path.relative_to(ROOT)}: {len(rows)} spells, build {build}')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
