#!/usr/bin/env python3
"""Generate the WowSims transport data (Lua) from its pinned JSON sources.

Rotation Master converts to and from WowSims APL JSON with the same declarative
rule table as the Rotation Master website (wowsims/mapping.json there). The
addon carries a pinned copy of that data under Data/wowsims/ and turns it into
the Lua tables the load-on-demand module Modules/RotationMaster_WowSims reads:

  Data/wowsims/mapping.json   the rule table (website, verbatim)
  Data/wowsims/kinds.json     the APL kinds each simulator reads (website, verbatim)
  Data/wowsims/ids.json       the spell ids each simulator's source names, per class,
                              with rank ladders and mana potions (reduced from the
                              website's wowsims/ids/*.json; item ids are left out,
                              the game client confirms those)
  Data/wowsims/SOURCE.json    where the pinned copies came from and their hashes

  Modules/RotationMaster_WowSims/mapping.lua   generated from mapping.json + kinds.json
  Modules/RotationMaster_WowSims/ids.lua       generated from ids.json

  python3 tools/export_wowsims_mapping.py            write the two Lua files
  python3 tools/export_wowsims_mapping.py --check    fail when the Lua files, the
                                                     pinned JSON or SOURCE.json disagree
  python3 tools/export_wowsims_mapping.py --refresh PATH
        re-pin from a checkout of the website (PATH/wowsims/...), record its commit
        and the hashes of what was read, then write the Lua files. Review the diff;
        the golden tests (tests/wowsims_golden.lua) say what a changed rule did.

The generator is deterministic: sorted keys, fixed formatting, no timestamps.
"""
import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'Data' / 'wowsims'
MODULE = ROOT / 'Modules' / 'RotationMaster_WowSims'
EDITIONS = ['era', 'tbc', 'progression', 'forever']
RESERVED = {'and', 'break', 'do', 'else', 'elseif', 'end', 'false', 'for', 'function', 'if', 'in', 'local', 'nil',
            'not', 'or', 'repeat', 'return', 'then', 'true', 'until', 'while'}
HEADER = ('-- Generated by tools/export_wowsims_mapping.py from {sources}.\n'
          '-- Do not edit: change the pinned JSON (Data/wowsims/) and regenerate.\n'
          'local _, ns = ...\n')


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def lua_key(key):
    if re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', key) and key not in RESERVED:
        return key
    return '[' + lua_string(key) + ']'


def lua_string(text):
    out = ['"']
    for ch in text:
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif ch == '\n':
            out.append('\\n')
        elif ord(ch) < 32 or ord(ch) == 127:
            out.append('\\%03d' % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return ''.join(out)


def lua_number(value):
    if isinstance(value, bool):
        raise ValueError('bool is not a number')
    if isinstance(value, int):
        return str(value)
    if value == int(value) and abs(value) < 1e15:
        return str(int(value))
    return repr(value)


def lua_value(value, indent=0, zero_based=False):
    """A JSON value as Lua. null becomes false (the rule table reads it that way)."""
    pad = '  ' * (indent + 1)
    end = '  ' * indent
    if value is None:
        return 'false'
    if value is True:
        return 'true'
    if value is False:
        return 'false'
    if isinstance(value, (int, float)):
        return lua_number(value)
    if isinstance(value, str):
        return lua_string(value)
    if isinstance(value, list):
        if not value:
            return '{}'
        if zero_based:
            # An enum table read by the protocol's 0-based number: explicit indexes, holes where null.
            items = ['[%d] = %s' % (i, lua_value(v, indent + 1)) for i, v in enumerate(value) if v is not None]
            return '{\n' + ''.join(pad + item + ',\n' for item in items) + end + '}'
        if all(isinstance(v, (int, float, str)) and not isinstance(v, bool) for v in value) and len(value) <= 12:
            return '{' + ', '.join(lua_value(v) for v in value) + '}'
        return '{\n' + ''.join(pad + lua_value(v, indent + 1) + ',\n' for v in value) + end + '}'
    if isinstance(value, dict):
        if not value:
            return '{}'
        items = []
        for key in sorted(value):
            items.append(pad + lua_key(key) + ' = ' + lua_value(value[key], indent + 1) + ',\n')
        return '{\n' + ''.join(items) + end + '}'
    raise TypeError(type(value))


def emit_dict_with_tableorder(mapping):
    # tableOrder's children are arrays that lua_value renders 0-based; handle that one key by hand.
    lines = []
    for key in sorted(mapping):
        value = mapping[key]
        if key == 'tableOrder':
            inner = []
            for name in sorted(value):
                inner.append('    ' + lua_key(name) + ' = ' + lua_value(value[name], 2, zero_based=True) + ',\n')
            lines.append('  tableOrder = {\n' + ''.join(inner) + '  },\n')
        else:
            lines.append('  ' + lua_key(key) + ' = ' + lua_value(value, 1) + ',\n')
    return '{\n' + ''.join(lines) + '}'


def delta_string(ids):
    """Sorted unique ids as 'first,delta,delta,...' (decimal)."""
    ordered = sorted(set(ids))
    out, previous = [], 0
    for value in ordered:
        out.append(str(value - previous))
        previous = value
    return ','.join(out)


def ladder_string(ladder):
    """One spell rank ladder: ids in rank order, 'id/rank' only where the rank is not the position."""
    parts = []
    for position, (spell, rank) in enumerate(ladder, 1):
        parts.append(str(spell) if rank == position else '%d/%d' % (spell, rank))
    return ','.join(parts)


def reduce_ids(site_ids):
    """The website's per-edition id files reduced to what the addon uses (no item ids)."""
    reduced = {}
    for edition in EDITIONS:
        data = json.loads((site_ids / f'{edition}.json').read_text(encoding='utf-8'))
        sources, seen, ladders, potions = [], set(), [], set()
        for src in data['sources']:
            spells = {cls: sorted(set(ids)) for cls, ids in sorted(src.get('spells', {}).items())}
            sources.append({'repo': src['repo'], 'ref': src.get('ref', ''), 'url': src.get('url', ''),
                            'spells': spells, 'items': len(src.get('items', []))})
            for ladder in src.get('ladders', []):
                key = tuple(map(tuple, ladder))
                if key not in seen:
                    seen.add(key)
                    ladders.append([list(pair) for pair in ladder])
            potions.update(src.get('manaPotions', []))
        reduced[edition] = {'sources': sources, 'ladders': ladders, 'manaPotions': sorted(potions, reverse=True)}
    return reduced


def minimal_json(value):
    return json.dumps(value, sort_keys=True, separators=(',', ':'), ensure_ascii=False) + '\n'


def generate_mapping_lua():
    mapping = json.loads((DATA / 'mapping.json').read_text(encoding='utf-8'))
    # Object key order is data the converter reads (the order editions are tried in): keep it as a list.
    mapping['editionOrder'] = list(mapping['editions'])
    kinds = json.loads((DATA / 'kinds.json').read_text(encoding='utf-8'))
    kinds_lua = {}
    for name, sim in sorted(kinds['sims'].items()):
        kinds_lua[name] = {'edition': sim['edition'], 'values': sim['values'], 'actions': sim['actions']}
    text = HEADER.format(sources='Data/wowsims/mapping.json and Data/wowsims/kinds.json')
    text += '\nns.mapping = ' + emit_dict_with_tableorder(mapping) + '\n'
    text += '\nns.kinds = {\n'
    for name, sim in sorted(kinds_lua.items()):
        text += '  [%s] = {\n    edition = %s,\n' % (lua_string(name), lua_string(sim['edition']))
        for field in ('values', 'actions'):
            text += '    %s = {\n' % field
            names = sim[field]
            for i in range(0, len(names), 4):
                text += '      ' + ', '.join(lua_string(n) for n in names[i:i + 4]) + ',\n'
            text += '    },\n'
        text += '  },\n'
    text += '}\n'
    return text


def generate_ids_lua():
    ids = json.loads((DATA / 'ids.json').read_text(encoding='utf-8'))
    text = HEADER.format(sources='Data/wowsims/ids.json')
    text += ('\n-- Spell ids the simulators\' sources name, per edition, source and class, as sorted ids written\n'
             '-- "first,delta,delta,..." and decoded on use (ns.ids). Ladders: ids in rank order, "id/rank" where the\n'
             '-- rank is not the position. Item ids are not shipped: the game client confirms those.\n')
    text += 'ns.idData = {\n'
    for edition in EDITIONS:
        entry = ids[edition]
        text += '  %s = {\n    sources = {\n' % edition
        for src in entry['sources']:
            text += '      {\n        repo = %s, ref = %s, url = %s, items = %d,\n        spells = {\n' % (
                lua_string(src['repo']), lua_string(src['ref']), lua_string(src['url']), src['items'])
            for cls in sorted(src['spells']):
                text += '          %s = %s,\n' % (lua_key(cls), lua_string(delta_string(src['spells'][cls])))
            text += '        },\n      },\n'
        text += '    },\n    ladders = {\n'
        for ladder in entry['ladders']:
            text += '      %s,\n' % lua_string(ladder_string(ladder))
        text += '    },\n    manaPotions = {%s},\n  },\n' % ', '.join(str(p) for p in entry['manaPotions'])
    text += '}\n'
    return text


def expected_files():
    return {MODULE / 'mapping.lua': generate_mapping_lua(), MODULE / 'ids.lua': generate_ids_lua()}


def source_problems():
    problems = []
    source_path = DATA / 'SOURCE.json'
    if not source_path.is_file():
        return ['Data/wowsims/SOURCE.json is missing']
    source = json.loads(source_path.read_text(encoding='utf-8'))
    for name in ('mapping.json', 'kinds.json', 'ids.json'):
        path = DATA / name
        recorded = source.get('pinned', {}).get(name)
        if not path.is_file():
            problems.append(f'Data/wowsims/{name} is missing')
        elif recorded != sha256(path):
            problems.append(f'Data/wowsims/{name} differs from the hash SOURCE.json records (edited by hand? '
                            f're-pin with --refresh)')
    return problems


def check():
    problems = source_problems()
    for path, text in expected_files().items():
        if not path.is_file():
            problems.append(f'{path.relative_to(ROOT)} is missing; run tools/export_wowsims_mapping.py')
        elif path.read_text(encoding='utf-8') != text:
            problems.append(f'{path.relative_to(ROOT)} is stale; run tools/export_wowsims_mapping.py')
    if problems:
        print('\n'.join(problems), file=sys.stderr)
        return 1
    print('WowSims data: Lua matches the pinned JSON')
    return 0


def refresh(site):
    site = Path(site).resolve()
    wowsims = site / 'wowsims'
    if not (wowsims / 'mapping.json').is_file():
        raise SystemExit(f'{site} does not look like the Rotation Master website checkout (no wowsims/mapping.json)')
    commit = subprocess.run(['git', '-C', str(site), 'rev-parse', 'HEAD'], capture_output=True, text=True).stdout.strip()
    dirty = subprocess.run(['git', '-C', str(site), 'status', '--porcelain', '--', 'wowsims'], capture_output=True,
                           text=True).stdout.strip()
    if dirty:
        raise SystemExit('the website checkout has uncommitted changes under wowsims/; commit them first so the '
                         'recorded commit says what was read')
    DATA.mkdir(parents=True, exist_ok=True)
    originals = {}
    for name in ('mapping.json', 'kinds.json'):
        (DATA / name).write_bytes((wowsims / name).read_bytes())
        originals[name] = sha256(wowsims / name)
    for edition in EDITIONS:
        originals[f'ids/{edition}.json'] = sha256(wowsims / 'ids' / f'{edition}.json')
    (DATA / 'ids.json').write_text(minimal_json(reduce_ids(wowsims / 'ids')), encoding='utf-8')
    source = {
        'note': 'Where the pinned WowSims transport data came from. mapping.json and kinds.json are byte copies of '
                'the website files; ids.json is reduced from the website ids/<edition>.json (spell ids only). '
                'The "origin" hashes are those of the website files that were read; "pinned" are the hashes of the '
                'copies here (tools/export_wowsims_mapping.py --check fails when they differ). The simulator data '
                'is MIT licensed (Copyright (c) wowsims team), see LICENSE-wowsims-MIT.txt.',
        'website': {'repository': 'rotationmaster website (wowsims/)', 'commit': commit},
        'origin': originals,
        'pinned': {name: sha256(DATA / name) for name in ('mapping.json', 'kinds.json', 'ids.json')},
        'refresh': 'python3 tools/export_wowsims_mapping.py --refresh <website checkout>',
    }
    license_src = wowsims / 'ids' / 'LICENSE-wowsims-MIT.txt'
    if license_src.is_file():
        (DATA / 'LICENSE-wowsims-MIT.txt').write_bytes(license_src.read_bytes())
    (DATA / 'SOURCE.json').write_text(json.dumps(source, indent=1, sort_keys=True, ensure_ascii=False) + '\n',
                                      encoding='utf-8')
    write()


def write():
    MODULE.mkdir(parents=True, exist_ok=True)
    for path, text in expected_files().items():
        path.write_text(text, encoding='utf-8')
        print(f'wrote {path.relative_to(ROOT)} ({len(text) / 1024:.1f} KB)')


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--refresh', metavar='SITE')
    args = parser.parse_args()
    if args.check:
        raise SystemExit(check())
    if args.refresh:
        refresh(args.refresh)
        return
    write()


if __name__ == '__main__':
    main()
